#!/usr/bin/env python3
"""Rebuilds google-sheet/Code.gs (the file you paste into the Google Sheet).

Run it after changing app/js/recipes.js, app/js/report.js, app/config.json
or google-sheet/server.js:

    python3 tools/build_apps_script.py

This keeps the recipe math and the report identical in the app and the email.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(*parts):
    with open(os.path.join(ROOT, *parts), encoding="utf-8") as f:
        return f.read()


def as_plain_script(src):
    """Turn an ES module into plain script: drop imports, drop the word 'export'."""
    out = []
    for line in src.splitlines():
        if line.startswith("import "):
            continue
        out.append(re.sub(r"^export\s+", "", line))
    return "\n".join(out).strip() + "\n"


def to_ascii(text):
    """Write every non-ASCII character as a \\uXXXX escape.

    The file is copied and pasted into Google, and some Mac copy tools read it as
    "Mac Roman", which garbles "·" into "¬∑" and Hindi into "‡§...". With only
    ASCII in the file, any copy method gives the same text. JavaScript reads the
    escapes back as the real characters (they are only in strings and comments).
    """
    out = []
    for ch in text:
        cp = ord(ch)
        if cp < 128:
            out.append(ch)
        elif cp < 0x10000:
            out.append("\\u%04x" % cp)
        else:
            cp -= 0x10000
            out.append("\\u%04x\\u%04x" % (0xD800 + (cp >> 10), 0xDC00 + (cp & 0x3FF)))
    return "".join(out)


def main():
    config = json.loads(read("app", "config.json"))
    seed = {k: config[k] for k in ("appName", "ownerPin", "categoryColors", "materials", "products", "workers") if k in config}
    parts = [
        "// PRISM – paste this whole file into the Google Sheet (Extensions > Apps Script).",
        "// GENERATED by tools/build_apps_script.py – edit the source files, not this one:",
        "//   app/js/recipes.js, app/js/report.js, app/config.json, google-sheet/server.js",
        "",
        "// ---- Starting data for a new sheet (from app/config.json) ----",
        "const SEED_CONFIG = " + json.dumps(seed, ensure_ascii=False, indent=2) + ";",
        "",
        "// ---- Shared with the app: app/js/recipes.js ----",
        as_plain_script(read("app", "js", "recipes.js")),
        "// ---- Shared with the app: app/js/report.js ----",
        as_plain_script(read("app", "js", "report.js")),
        "// ---- Sheet side: google-sheet/server.js ----",
        read("google-sheet", "server.js").strip(),
        "",
    ]
    text = to_ascii("\n".join(parts))
    out_path = os.path.join(ROOT, "google-sheet", "Code.gs")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    print("Wrote google-sheet/Code.gs (%d lines)" % text.count("\n"))


if __name__ == "__main__":
    main()
